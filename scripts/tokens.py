"""Writes assets/brand/tokens.css from tokens.json, after checking contrast.

Light values sit on :root; dark ones follow the OS unless a page sets
data-theme, which wins either way.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BRAND = ROOT / "assets" / "brand"
REF = re.compile(r"\{([a-z0-9.-]+)\}")


def var_name(path):
    layer, *rest = path
    if layer == "primitive" and rest[0] in ("color", "font"):
        rest = rest[1:]
    return "--" + "-".join(rest)


def leaves(node, path=()):
    for key, value in node.items():
        if key.startswith("$"):
            continue
        if "$value" in value:
            yield path + (key,), value["$value"]
        else:
            yield from leaves(value, path + (key,))


def css_value(value):
    return REF.sub(lambda m: f"var({var_name(m.group(1).split('.'))})", value)


def block(selector, entries, indent="", extra=()):
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  {var_name(path)}: {css_value(value)};" for path, value in entries]
    lines += [f"{indent}  {line}" for line in extra]
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def luminance(hex_colour):
    channels = [int(hex_colour[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    r, g, b = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def ratio(a, b):
    high, low = sorted((luminance(a), luminance(b)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def resolve(tokens, value):
    while (m := REF.fullmatch(value)):
        node = tokens
        for key in m.group(1).split("."):
            node = node[key]
        value = node["$value"]
    return value


def check_contrast(tokens):
    light = tokens["semantic"]["color"]
    themes = {"light": light, "dark": {**light, **tokens["dark"]["semantic"]["color"]}}
    failures = []
    for theme, colours in themes.items():
        for fg, bg, minimum in tokens["$contrast"]["pairs"]:
            got = ratio(resolve(tokens, colours[fg]["$value"]), resolve(tokens, colours[bg]["$value"]))
            if got < minimum:
                failures.append(f"{theme}: {fg} on {bg} is {got:.2f}, needs {minimum}")
    return failures


def main():
    tokens = json.loads((BRAND / "tokens.json").read_text())
    if failures := check_contrast(tokens):
        sys.exit("contrast:\n  " + "\n  ".join(failures))

    root = [*leaves(tokens["primitive"], ("primitive",)),
            *leaves(tokens["semantic"], ("semantic",)),
            *leaves(tokens["component"], ("component",))]
    dark = list(leaves(tokens["dark"]["semantic"], ("semantic",)))
    css = "\n\n".join([
        "/* Generated by scripts/tokens.py from tokens.json; edit that, then run `make brand`. */",
        block(":root", root),
        "@media (prefers-color-scheme: dark) {\n"
        + block(':root:not([data-theme="light"])', dark, "  ", ["color-scheme: dark;"]) + "\n}",
        block(':root[data-theme="dark"]', dark, extra=["color-scheme: dark;"]),
    ]) + "\n"
    (BRAND / "tokens.css").write_text(css)


if __name__ == "__main__":
    main()
